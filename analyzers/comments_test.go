func metadataAndCgoSource(identifier string) string {
	signature := "Generated by " + identifier + "."
	generatedMarker := "// Code generated by " + identifier + ". DO NOT EDIT."
	sourceLines := []string{
		generatedMarker,
		"package p",
		"",
		"//go:generate echo " + signature,
		"",
		"/*",
		signature,
		"*/",
		`import "C"`,
	}
	return strings.Join(sourceLines, "\n")
}

