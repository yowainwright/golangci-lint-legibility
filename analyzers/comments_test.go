func TestNoAutomatedCommentAttributionReportsSignatures(t *testing.T) {
	source := automatedSignatureSource()
	analyzer := analyzerByRule(t, "no-automated-comment-attribution")
	diagnostics := runAnalyzer(t, analyzer, "p.go", source)
	requireDiagnosticsCount(t, diagnostics, 2)
	requireDiagnostic(t, diagnostics, "LEG040 no-automated-comment-attribution")
}

func automatedSignatureSource() string {
	firstIdentifier := "chat" + "gpt"
	secondIdentifier := "clau" + "de"
	signature := "Generated by " + firstIdentifier
	generatedComment := "// " + signature + "."
	author := "@" + "author " + secondIdentifier
	authorLine := " * " + author
	sourceLines := []string{
		"package p",
		generatedComment,
		"func first() {}",
		"",
		"/*",
		authorLine,
		" */",
		"func second() {}",
	}
	return strings.Join(sourceLines, "\n")
}

func TestNoAutomatedCommentAttributionIgnoresTechnologyReferences(t *testing.T) {
	identifier := "chat" + "gpt"
	author := "@" + "author Jeff"
	request := "Send a request to " + identifier
	sentence := request + "."
	commentPrefix := "// " + sentence
	comment := commentPrefix + " " + author
	sourceLines := []string{"package p", comment, "func value() {}"}
	source := strings.Join(sourceLines, "\n")

	analyzer := analyzerByRule(t, "no-automated-comment-attribution")
	diagnostics := runAnalyzer(t, analyzer, "p.go", source)
	requireDiagnosticsCount(t, diagnostics, 0)
}

